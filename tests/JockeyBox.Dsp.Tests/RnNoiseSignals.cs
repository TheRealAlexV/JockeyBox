namespace JockeyBox.Dsp.Tests;

/// <summary>
/// Deterministic signals split by how the denoiser treats them, so an assertion can be matched
/// to a class the network is known to respond to.
/// <para>
/// <b>The rule:</b> an energy assertion may only use a signal class the denoiser is known to
/// transform in that direction. A signal can be wrong for an assertion even when the code is
/// right; three gate runs were spent learning that. Ask which class the assertion needs before
/// asking whether the code is correct.
/// </para>
/// <list type="bullet">
/// <item>
/// <b>Suppressive</b> — noise-like. Measured on the rig at int16 scale: <b>−68.94 dB</b>. Use it
/// for “the denoiser removed energy”, never for a pass-through or correlation claim.
/// </item>
/// <item>
/// <b>Voiced</b> — periodic/formant. Measured <b>+0.02 dB</b> normalised and <b>−8.58 dB</b>
/// int16. The network passes it, so use it for latency correlation and bit-exact comparisons;
/// it must not carry an “it removed energy” bound.
/// </item>
/// </list>
/// Everything is generated by a fixed LCG, so two runs are bit-identical.
/// </summary>
internal static class RnNoiseSignals
{
    public const int FrameSize = 480;
    public const float Int16Scale = 32768f;

    /// <summary>
    /// Noise-like signal in <c>[-1,1]</c>, deterministic. This is the class the network
    /// attenuates. Multiply by <see cref="Int16Scale"/> (or call <see cref="ToInt16"/>) before
    /// handing it to the raw engine.
    /// </summary>
    public static float[] Suppressive(int frames, int seed, float amplitude = 0.3f)
    {
        var x = new float[frames * FrameSize];
        uint state = unchecked((uint)seed * 2654435761u + 1u);
        for (int i = 0; i < x.Length; i++)
        {
            state = unchecked(state * 1664525u + 1013904223u);
            x[i] = ((state >> 9) / 8388608f - 1f) * amplitude;
        }

        return x;
    }

    /// <summary>
    /// Periodic/formant signal in <c>[-1,1]</c>: a jittered glottal pulse train through two
    /// formant resonators. The jitter keeps it non-periodic so cross-correlation has a unique
    /// peak; the network treats it as voice and passes it. Deterministic.
    /// </summary>
    public static float[] Voiced(int samples, float amplitude = 0.6f)
    {
        var x = new float[samples];
        int k = 0;
        uint state = 0x9E3779B9u;
        while (k < samples)
        {
            x[k] = 1f;
            state = unchecked(state * 1664525u + 1013904223u);
            k += 350 + (int)((state >> 16) % 100);
        }

        Resonate(x, 700, 80);
        Resonate(x, 1220, 100);

        double peak = 0;
        foreach (float v in x) peak = Math.Max(peak, Math.Abs(v));
        if (peak > 0) for (int i = 0; i < samples; i++) x[i] = (float)(x[i] / peak * amplitude);
        return x;
    }

    /// <summary>Converts a <c>[-1,1]</c> buffer to the int16 scale the raw engine expects.</summary>
    public static float[] ToInt16(float[] samples)
    {
        var x = (float[])samples.Clone();
        for (int i = 0; i < x.Length; i++) x[i] *= Int16Scale;
        return x;
    }

    private static void Resonate(float[] x, double frequencyHz, double bandwidthHz)
    {
        const double sampleRate = 48000;
        double r = Math.Exp(-Math.PI * bandwidthHz / sampleRate);
        double c = 2 * r * Math.Cos(2 * Math.PI * frequencyHz / sampleRate);
        double y1 = 0, y2 = 0;
        for (int i = 0; i < x.Length; i++)
        {
            double y = x[i] + c * y1 - r * r * y2;
            x[i] = (float)y;
            y2 = y1;
            y1 = y;
        }
    }
}
